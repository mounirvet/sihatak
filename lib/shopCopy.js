// CATEGORY_REVIEWS — REMOVED.
// This shipped invented customer testimonials on all 32 products: fake initials
// ("م. ع", "ن. س") attached to fake quotes about orders nobody placed. It was
// labelled "honest STARTER reviews ... to be replaced", but it was live on a
// YMYL health site, and a visitor cannot tell a placeholder testimonial from a
// real one.
// If real reviews are ever collected, add a `reviews:` array to the product
// frontmatter and render from that. Never from a default.

export function getSellCopy(p) {
  const cat = p.category;
  return {
    tagline: p.hero_tagline || CATEGORY_TAGLINE[cat] || null,
    heroClaim: p.hero_claim || CATEGORY_HERO_CLAIM[cat] || null,
    sellBenefits:
      (Array.isArray(p.benefits) && p.benefits.length
        ? p.benefits.map((b) => (Array.isArray(b) ? b : [b.icon, b.title, b.text]))
        : CATEGORY_SELL_BENEFITS[cat]) || [],
    howTo:
      (Array.isArray(p.how_to) && p.how_to.length
        ? p.how_to.map((h) => (Array.isArray(h) ? h : [h.title, h.detail]))
        : CATEGORY_HOW_TO[cat]) || [],
    // Only REAL reviews, from the product's own frontmatter. No category
    // fallback: an empty array means no reviews section renders, which is the
    // correct outcome when a product has no reviews.
    reviews: Array.isArray(p.reviews) && p.reviews.length
      ? p.reviews.map((r) => (Array.isArray(r) ? r : [r.name, r.text]))
      : [],
  };
}
